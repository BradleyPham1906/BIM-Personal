  // ---- __acad3dV9: mitered wall corners. Replaces the old per-segment CSG-union wall body with a single
  // ribbon mesh built directly from the (already-mitered) offset rings above, so corners are a genuine
  // sharp miter rather than an overlapping-box CSG seam. meshPolys' signed-volume pass (see below) fixes
  // overall winding automatically, so getting the outward-vs-inward face direction here isn't safety-critical. ----
  function bimBuildWallRibbonMesh(outer,inner,y0,height,closed){
    var n=outer.length;
    if(n!==inner.length||n<2)return null;
    var v=[],f=[],i;
    var segCount=closed?n:n-1;
    for(i=0;i<n;i++)v.push([outer[i][0],y0,outer[i][1]]);
    for(i=0;i<n;i++)v.push([outer[i][0],y0+height,outer[i][1]]);
    for(i=0;i<n;i++)v.push([inner[i][0],y0,inner[i][1]]);
    for(i=0;i<n;i++)v.push([inner[i][0],y0+height,inner[i][1]]);
    var OB=0,OT=n,IB=2*n,IT=3*n;
    for(i=0;i<segCount;i++){
      var j=(i+1)%n;
      f.push([OB+j,OB+i,OT+i,OT+j]);
      f.push([IB+i,IB+j,IT+j,IT+i]);
      f.push([OT+j,OT+i,IT+i,IT+j]);
      f.push([OB+i,OB+j,IB+j,IB+i]);
    }
    if(!closed){
      f.push([OB+0,IB+0,IT+0,OT+0]);
      var last=n-1;
      f.push([IB+last,OB+last,OT+last,IT+last]);
    }
    return {v:v,f:f};
  }
